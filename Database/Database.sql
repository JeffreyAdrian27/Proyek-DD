--data helm

CREATE TABLE SPAREPART (
	ID_SPAREPART NUMBER(3) PRIMARY KEY,
	NAMA_SPAREPART VARCHAR2(20),
	STOK NUMBER(3),
	HARGA NUMBER(10),
	KETERANGAN VARCHAR2(255)
);

CREATE TABLE MODEL_HELM (
	ID_MODEL NUMBER(3) PRIMARY KEY,
	NAMA_MODEL VARCHAR2(20)
);

CREATE TABLE PRODUSEN (
	ID_PRODUSEN NUMBER(3) PRIMARY KEY,
	NAMA_PRODUSEN VARCHAR2(20)
);

CREATE TABLE HELM (
	ID_HELM NUMBER(3) PRIMARY KEY,
	NAMA_HELM VARCHAR2(255),
	ID_MODEL NUMBER(3),
	ID_PRODUSEN NUMBER(3),
	STOK NUMBER(10),
	HARGA NUMBER(10),
	FOREIGN KEY (ID_MODEL) REFERENCES MODEL_HELM(ID_MODEL),
	FOREIGN KEY (ID_PRODUSEN) REFERENCES PRODUSEN(ID_PRODUSEN)
);

-------------------------------------------------------------
--servis

CREATE TABLE TRANS_SERVIS (
	NO_TRANS_SERVIS VARCHAR2(20) PRIMARY KEY,
	NO_TRANS_JUAL VARCHAR2(20),
	ID_HELM NUMBER(10),
	ID_CUSTOMER VARCHAR2(3),
	ID_KARYAWAN VARCHAR2(3),
	TGL_SERVIS DATE,
	KETERANGAN VARCHAR2(255),
	BIAYA NUMBER(10),
	FOREIGN KEY (ID_HELM) REFERENCES HELM(ID_HELM),
	FOREIGN KEY (ID_CUSTOMER) REFERENCES CUSTOMER_SERVIS(ID_CUSTOMER),
	FOREIGN KEY (ID_KARYAWAN) REFERENCES KARYAWAN_SERVIS(ID_KARYAWAN)
);

-------------------------------------------------------------
--cuci

CREATE TABLE TRANS_CUCI (
	NO_TRANS_CUCI VARCHAR2(20) PRIMARY KEY,
	NO_TRANS_JUAL VARCHAR2(20),
	ID_HELM NUMBER(10),
	ID_CUSTOMER VARCHAR2(3),
	ID_KARYAWAN VARCHAR2(3),
	TGL_CUCI DATE,
	KETERANGAN VARCHAR2(255),
	BIAYA NUMBER(10),
	FOREIGN KEY (ID_HELM) REFERENCES HELM(ID_HELM),
	FOREIGN KEY (ID_CUSTOMER) REFERENCES CUSTOMER_CUCI(ID_CUSTOMER),
	FOREIGN KEY (ID_KARYAWAN) REFERENCES KARYAWAN_CUCI(ID_KARYAWAN)
);

-------------------------------------------------------------
--jual

CREATE TABLE H_TRANS_JUAL (
	NO_TRANS_JUAL VARCHAR2(3) PRIMARY KEY,
	TGL_JUAL DATE,
	ID_HELM VARCHAR2(3),
	ID_CUSTOMER VARCHAR2(3),
	ID_KARYAWAN VARCHAR2(3),
	SUBTOTAL_HARGA NUMBER(10),
	FOREIGN KEY (ID_HELM) REFERENCES HELM(ID_HELM),
	FOREIGN KEY (ID_CUSTOMER) REFERENCES CUSTOMER_JUAL(ID_CUSTOMER),
	FOREIGN KEY (ID_KARYAWAN) REFERENCES KARYAWAN_JUAL(ID_KARYAWAN)
);

CREATE TABLE D_TRANS_JUAL (
	NO_TRANS_JUAL VARCHAR2(3),
	ID_HELM VARCHAR2(3),
	JUMLAH NUMBER(10),
	FOREIGN KEY (ID_HELM) REFERENCES HELM(ID_HELM),
	FOREIGN KEY (NO_TRANS_JUAL) REFERENCES H_TRANS_JUAL(NO_TRANS_JUAL)
);



